export function applyAccent(key) {
  const preset = ACCENT_PRESETS[key]
  if (!preset) return
  const root = document.documentElement
  for (const [shade, rgb] of Object.entries(preset.scale)) {
    root.style.setProperty(`--c-primary-${shade}`, rgb)
  }
}
